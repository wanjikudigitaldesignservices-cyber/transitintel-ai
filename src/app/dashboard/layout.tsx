export default function DashboardLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const router = useRouter();
  const pathname = usePathname();
  const { data: session, status } = useSession();
  const [sidebarOpen, setSidebarOpen] = useState(true);
  const [mobileSidebarOpen, setMobileSidebarOpen] = useState(false);
  const [darkMode, setDarkMode] = useState(true);

  useEffect(() => {
    if (status === "unauthenticated") {
      router.push("/login");
    }
  }, [status, router]);

  useEffect(() => {
    document.documentElement.classList.toggle("dark", darkMode);
  }, [darkMode]);

  const handleLogout = () => {
    signOut({ callbackUrl: "/login" });
  };

  const user = session?.user as { name?: string | null; email?: string | null; role?: string; organizationName?: string } | undefined;

  if (status === "loading" || !user) {
    return (
      <div className="dark flex h-screen items-center justify-center bg-surface-950">
        <div className="h-8 w-8 animate-spin rounded-full border-2 border-brand-500 border-t-transparent" />
      </div>
    );
  }

  return (
    <div className={`${darkMode ? "dark" : ""}`}>
      <div className="flex h-screen overflow-hidden bg-surface-50 dark:bg-surface-950">
        {/* Mobile Overlay */}
        {mobileSidebarOpen && (
          <div
            className="fixed inset-0 z-40 bg-black/50 backdrop-blur-sm lg:hidden"
            onClick={() => setMobileSidebarOpen(false)}
          />
        )}

        {/* Sidebar */}
        <aside
          className={`sidebar fixed inset-y-0 left-0 z-50 flex flex-col transition-all duration-300 lg:relative lg:z-auto
            ${sidebarOpen ? "w-64" : "w-20"}
            ${mobileSidebarOpen ? "translate-x-0" : "-translate-x-full lg:translate-x-0"}
          `}
        >
          {/* Logo */}
          <div className="flex h-16 items-center gap-3 border-b border-white/5 px-4">
            <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-brand-500 text-sm font-bold text-white">
              TI
            </div>
            {sidebarOpen && (
              <span className="text-sm font-bold text-white animate-fade-in">
                TransitIntel <span className="text-brand-400">AI</span>
              </span>
            )}
          </div>

          {/* Nav Links */}
          <nav className="flex-1 overflow-y-auto px-3 py-4">
            <div className="space-y-1">
              {NAVIGATION.map((item) => {
                const isActive =
                  pathname === item.href ||
                  (item.href !== "/dashboard" &&
                    pathname.startsWith(item.href));
                return (
                  <Link
                    key={item.href}
                    href={item.href}
                    className={`sidebar-link relative ${isActive ? "active" : ""}`}
                    title={!sidebarOpen ? item.title : undefined}
                    onClick={() => setMobileSidebarOpen(false)}
                  >
                    <span className="shrink-0">
                      {icons[item.icon] || icons.LayoutDashboard}
                    </span>
                    {sidebarOpen && (
                      <span className="animate-fade-in">{item.title}</span>
                    )}
                  </Link>
                );
              })}
            </div>
          </nav>

          {/* Sidebar Footer */}
          <div className="border-t border-white/5 p-3">
            <button
              onClick={() => setSidebarOpen(!sidebarOpen)}
              className="hidden w-full items-center justify-center rounded-lg p-2 text-white/40 transition hover:bg-white/5 hover:text-white/70 lg:flex"
            >
              <svg
                className={`h-5 w-5 transition-transform ${!sidebarOpen ? "rotate-180" : ""}`}
                fill="none"
                viewBox="0 0 24 24"
                stroke="currentColor"
                strokeWidth={1.5}
              >
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M18.75 19.5l-7.5-7.5 7.5-7.5m-6 15L5.25 12l7.5-7.5"
                />
              </svg>
            </button>
          </div>
        </aside>

        {/* Main Area */}
        <div className="flex flex-1 flex-col overflow-hidden">
          {/* Top Bar */}
          <header className="flex h-16 shrink-0 items-center justify-between border-b border-surface-200 bg-white/80 px-4 backdrop-blur-xl dark:border-white/5 dark:bg-surface-950/80 lg:px-6">
            {/* Left: Hamburger + breadcrumb */}
            <div className="flex items-center gap-4">
              <button
                onClick={() => setMobileSidebarOpen(true)}
                className="rounded-lg p-2 text-surface-800/50 hover:bg-surface-100 dark:text-white/50 dark:hover:bg-white/5 lg:hidden"
              >
                <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
                  <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
                </svg>
              </button>
              <div>
                <h2 className="text-sm font-semibold text-surface-900 dark:text-white">
                  {NAVIGATION.find(
                    (n) =>
                      pathname === n.href ||
                      (n.href !== "/dashboard" && pathname.startsWith(n.href))
                  )?.title || "Dashboard"}
                </h2>
                <p className="text-xs text-surface-800/40 dark:text-white/30">
                  {user.organizationName || "TransitIntel"}
                </p>
              </div>
            </div>

            {/* Right: Actions */}
            <div className="flex items-center gap-3">
              {/* Dark Mode Toggle */}
              <button
                onClick={() => setDarkMode(!darkMode)}
                className="rounded-lg p-2 text-surface-800/50 transition hover:bg-surface-100 dark:text-white/50 dark:hover:bg-white/5"
                title="Toggle theme"
              >
                {darkMode ? (
                  <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
                    <path strokeLinecap="round" strokeLinejoin="round" d="M12 3v2.25m6.364.386l-1.591 1.591M21 12h-2.25m-.386 6.364l-1.591-1.591M12 18.75V21m-4.773-4.227l-1.591 1.591M5.25 12H3m4.227-4.773L5.636 5.636M15.75 12a3.75 3.75 0 11-7.5 0 3.75 3.75 0 017.5 0z" />
                  </svg>
                ) : (
                  <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
                    <path strokeLinecap="round" strokeLinejoin="round" d="M21.752 15.002A9.718 9.718 0 0118 15.75c-5.385 0-9.75-4.365-9.75-9.75 0-1.33.266-2.597.748-3.752A9.753 9.753 0 003 11.25C3 16.635 7.365 21 12.75 21a9.753 9.753 0 009.002-5.998z" />
                  </svg>
                )}
              </button>

              {/* Notifications */}
              <button className="relative rounded-lg p-2 text-surface-800/50 transition hover:bg-surface-100 dark:text-white/50 dark:hover:bg-white/5">
                <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
                  <path strokeLinecap="round" strokeLinejoin="round" d="M14.857 17.082a23.848 23.848 0 005.454-1.31A8.967 8.967 0 0118 9.75v-.7V9A6 6 0 006 9v.75a8.967 8.967 0 01-2.312 6.022c1.733.64 3.56 1.085 5.455 1.31m5.714 0a24.255 24.255 0 01-5.714 0m5.714 0a3 3 0 11-5.714 0" />
                </svg>
                <span className="absolute right-1.5 top-1.5 h-2 w-2 rounded-full bg-brand-500" />
              </button>

              {/* Profile */}
              <div className="flex items-center gap-3 border-l border-surface-200 pl-3 dark:border-white/10">
                <div className="hidden text-right sm:block">
                  <p className="text-sm font-medium text-surface-900 dark:text-white">
                    {user.name || "User"}
                  </p>
                  <p className="text-xs text-surface-800/40 dark:text-white/30">
                    {(user.role || "VIEWER").replace("_", " ")}
                  </p>
                </div>
                <button
                  onClick={handleLogout}
                  className="flex h-9 w-9 items-center justify-center rounded-full bg-brand-500/10 text-sm font-bold text-brand-500 transition hover:bg-brand-500/20"
                  title="Sign out"
                >
                  {(user.name || "U")
                    .split(" ")
                    .map((n) => n[0])
                    .join("")
                    .toUpperCase()
                    .slice(0, 2)}
                </button>
              </div>
            </div>
          </header>

          {/* Page Content */}
          <main className="flex-1 overflow-y-auto p-4 lg:p-6">
            <SocketProvider>{children}</SocketProvider>
          </main>
        </div>
      </div>
    </div>
  );
}
